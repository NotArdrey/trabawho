-- Rework is a separate, auditable case workflow. It never edits payment or
-- payout state and does not decide whether the original defect was covered.
alter table public.booking_support_cases
  add column rework_state text check (rework_state in (
    'appointment_proposed', 'appointment_accepted', 'rework_delivered',
    'resolved_by_client', 'escalated')),
  add column rework_appointment_at timestamptz,
  add column rework_evidence_note text,
  add column rework_evidence_path text,
  add column rework_delivered_at timestamptz,
  add column rework_confirmed_at timestamptz,
  add column rework_escalated_at timestamptz;

create table public.booking_case_actions (
  id bigint generated by default as identity primary key,
  case_id uuid not null references public.booking_support_cases(id) on delete restrict,
  actor_id uuid not null references auth.users(id),
  action text not null check (action in (
    'propose_appointment', 'accept_appointment', 'escalate',
    'submit_rework', 'confirm_rework')),
  note text,
  appointment_at timestamptz,
  storage_path text,
  operation_id text not null,
  created_at timestamptz not null default now(),
  unique (case_id, operation_id)
);
alter table public.booking_case_actions enable row level security;
create policy booking_case_actions_read on public.booking_case_actions
  for select to authenticated using (exists (
    select 1 from public.booking_support_cases c
    join public.bookings b on b.id = c.booking_id
    where c.id = case_id and (b.buyer_id = auth.uid()
      or b.seller_id = auth.uid() or public.is_current_user_admin())
  ));
revoke insert, update, delete on public.booking_case_actions from anon, authenticated;
grant select on public.booking_case_actions to authenticated;

create function public.advance_repair_rework(
  p_case_id uuid, p_action text, p_note text,
  p_appointment_at timestamptz, p_storage_path text, p_operation_id text
) returns public.booking_support_cases
language plpgsql security definer set search_path = public as $$
declare
  v_case public.booking_support_cases%rowtype;
  v_booking public.bookings%rowtype;
  v_prior public.booking_case_actions%rowtype;
  v_actor uuid := auth.uid();
  v_note text := nullif(trim(coalesce(p_note, '')), '');
begin
  if v_actor is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  if nullif(trim(coalesce(p_operation_id, '')), '') is null then
    raise exception 'Operation ID required' using errcode = '22023'; end if;
  if p_action is null or p_action not in ('propose_appointment',
    'accept_appointment', 'escalate', 'submit_rework', 'confirm_rework') then
    raise exception 'Unsupported rework action' using errcode = '22023'; end if;
  select * into v_case from public.booking_support_cases where id = p_case_id for update;
  if not found then raise exception 'Support case not found' using errcode = 'P0002'; end if;
  select * into v_booking from public.bookings where id = v_case.booking_id;
  if v_actor not in (v_booking.buyer_id, v_booking.seller_id) then
    raise exception 'Only booking participants may act on this case' using errcode = '42501'; end if;
  select * into v_prior from public.booking_case_actions
    where case_id = p_case_id and operation_id = p_operation_id;
  if found then
    if v_prior.actor_id <> v_actor or v_prior.action <> p_action
      or v_prior.note is distinct from v_note
      or v_prior.appointment_at is distinct from p_appointment_at
      or v_prior.storage_path is distinct from p_storage_path then
      raise exception 'Operation ID was already used for a different action' using errcode = '23505';
    end if;
    return v_case;
  end if;
  if v_case.case_type <> 'warranty_issue' or v_case.policy_route <> 'rework_request'
    or v_case.provider_response_action <> 'offer_rework' or v_case.status <> 'open' then
    raise exception 'This case is not in the repair rework flow' using errcode = '23514'; end if;
  if (p_action in ('propose_appointment', 'submit_rework') and v_actor <> v_booking.seller_id)
    or (p_action in ('accept_appointment', 'escalate', 'confirm_rework')
      and v_actor <> v_booking.buyer_id) then
    raise exception 'Only the next responsible participant may perform this action' using errcode = '42501'; end if;

  if p_action = 'propose_appointment' then
    if v_case.rework_state is not null or p_appointment_at is null
      or p_appointment_at <= now() + interval '30 minutes' then
      raise exception 'Propose a new appointment at least 30 minutes from now' using errcode = '23514'; end if;
    update public.booking_support_cases set rework_state = 'appointment_proposed',
      rework_appointment_at = p_appointment_at where id = p_case_id returning * into v_case;
  elsif p_action = 'accept_appointment' then
    if v_case.rework_state is distinct from 'appointment_proposed'
      or v_case.rework_appointment_at <= now() then
      raise exception 'This appointment is no longer available; ask support to review' using errcode = '23514'; end if;
    update public.booking_support_cases set rework_state = 'appointment_accepted'
      where id = p_case_id returning * into v_case;
  elsif p_action = 'submit_rework' then
    if v_case.rework_state is distinct from 'appointment_accepted'
      or now() < v_case.rework_appointment_at - interval '30 minutes'
      or length(coalesce(v_note, '')) < 20 then
      raise exception 'Submit rework notes after the accepted appointment begins' using errcode = '23514'; end if;
    if p_storage_path is not null and (
      split_part(p_storage_path, '/', 1) <> v_case.booking_id::text
      or split_part(p_storage_path, '/', 2) <> v_actor::text
      or not exists (select 1 from storage.objects where bucket_id = 'booking-evidence'
        and name = p_storage_path)
    ) then raise exception 'Rework image was not uploaded by this provider' using errcode = '23514'; end if;
    update public.booking_support_cases set rework_state = 'rework_delivered',
      rework_evidence_note = v_note, rework_evidence_path = p_storage_path,
      rework_delivered_at = now() where id = p_case_id returning * into v_case;
  elsif p_action = 'confirm_rework' then
    if v_case.rework_state is distinct from 'rework_delivered' then
      raise exception 'Rework evidence must be submitted before confirmation' using errcode = '23514'; end if;
    update public.booking_support_cases set rework_state = 'resolved_by_client',
      rework_confirmed_at = now(), status = 'closed', closed_at = now()
      where id = p_case_id returning * into v_case;
    if not exists (select 1 from public.booking_support_cases
      where booking_id = v_case.booking_id and id <> p_case_id and status <> 'closed') then
      perform set_config('app.booking_workflow_rpc', 'on', true);
      update public.bookings set dispute_status = 'closed'
        where id = v_case.booking_id and dispute_status = 'open';
    end if;
  else
    if v_case.rework_state in ('resolved_by_client', 'escalated')
      or length(coalesce(v_note, '')) < 20 then
      raise exception 'Explain why support review is needed in at least 20 characters' using errcode = '23514'; end if;
    update public.booking_support_cases set rework_state = 'escalated',
      rework_escalated_at = now(), status = 'under_review'
      where id = p_case_id returning * into v_case;
  end if;
  insert into public.booking_case_actions
    (case_id, actor_id, action, note, appointment_at, storage_path, operation_id)
    values (p_case_id, v_actor, p_action, v_note, p_appointment_at, p_storage_path, p_operation_id);
  insert into public.booking_audit_events
    (booking_id, event_type, actor_id, actor_role, reason, idempotency_key,
      from_status, to_status, event_data)
    values (v_case.booking_id, 'repair_rework_' || p_action, v_actor,
      case when v_actor = v_booking.seller_id then 'seller' else 'buyer' end,
      v_note, p_operation_id, v_booking.status, v_booking.status,
      jsonb_build_object('case_id', p_case_id, 'rework_state', v_case.rework_state,
        'appointment_at', p_appointment_at, 'evidence_path', p_storage_path));
  return v_case;
end;
$$;
revoke all on function public.advance_repair_rework(uuid, text, text, timestamptz, text, text) from public;
grant execute on function public.advance_repair_rework(uuid, text, text, timestamptz, text, text) to authenticated;
