-- Secure booking completion lifecycle.
-- Delivery is a seller claim; completion requires buyer confirmation or a
-- service-role auto-confirm job. Payment and dispute state are independent.

alter table public.bookings
  add column if not exists delivery_status text not null default 'not_delivered',
  add column if not exists payment_status text not null default 'unpaid',
  add column if not exists cash_collection_status text not null default 'not_applicable',
  add column if not exists dispute_status text not null default 'none',
  add column if not exists schedule_version integer not null default 1,
  add column if not exists delivered_schedule_version integer,
  add column if not exists delivered_at timestamptz,
  add column if not exists delivered_by uuid references auth.users(id),
  add column if not exists completion_due_at timestamptz,
  add column if not exists completed_at timestamptz,
  add column if not exists completed_by uuid references auth.users(id),
  add column if not exists dispute_opened_at timestamptz,
  add column if not exists dispute_opened_by uuid references auth.users(id),
  add column if not exists dispute_reason text,
  add column if not exists dispute_deadline_at timestamptz;

alter table public.bookings
  drop constraint if exists bookings_delivery_status_check,
  drop constraint if exists bookings_payment_status_check,
  drop constraint if exists bookings_cash_collection_status_check,
  drop constraint if exists bookings_dispute_status_check;

alter table public.bookings
  add constraint bookings_delivery_status_check
    check (delivery_status in ('not_delivered', 'seller_claimed', 'buyer_confirmed')),
  add constraint bookings_payment_status_check
    check (payment_status in ('unpaid', 'pending_provider', 'pending_buyer_acknowledgement', 'paid', 'refunded')),
  add constraint bookings_cash_collection_status_check
    check (cash_collection_status in ('not_applicable', 'awaiting_collection', 'seller_claimed', 'buyer_acknowledged')),
  add constraint bookings_dispute_status_check
    check (dispute_status in ('none', 'open', 'resolved_buyer', 'resolved_seller', 'closed')),
  add constraint bookings_schedule_version_check check (schedule_version > 0);

-- Grandfather existing records without trusting client metadata for new ones.
update public.bookings
set
  delivery_status = case when status = 'completed' then 'buyer_confirmed' else delivery_status end,
  payment_status = case
    when status = 'refunded' then 'refunded'
    when status = 'completed' or payment_reference is not null then 'paid'
    else payment_status
  end,
  cash_collection_status = case
    when coalesce(metadata->>'payment_method', '') = 'after-service-cash' and status = 'completed'
      then 'buyer_acknowledged'
    when coalesce(metadata->>'payment_method', '') = 'after-service-cash'
      then 'awaiting_collection'
    else 'not_applicable'
  end,
  delivered_at = case when status = 'completed' then coalesce(delivered_at, updated_at) else delivered_at end,
  completed_at = case when status = 'completed' then coalesce(completed_at, updated_at) else completed_at end,
  dispute_deadline_at = case
    when status = 'completed' then coalesce(dispute_deadline_at, updated_at + interval '48 hours')
    else dispute_deadline_at
  end;

create table if not exists public.booking_audit_events (
  id bigint generated by default as identity primary key,
  booking_id uuid not null references public.bookings(id) on delete restrict,
  event_type text not null,
  actor_id uuid references auth.users(id),
  actor_role text not null,
  reason text,
  idempotency_key text,
  from_status text,
  to_status text,
  event_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists booking_audit_events_booking_created_idx
  on public.booking_audit_events(booking_id, created_at desc);
create unique index if not exists booking_audit_events_idempotency_idx
  on public.booking_audit_events(
    booking_id,
    event_type,
    coalesce(actor_id, '00000000-0000-0000-0000-000000000000'::uuid),
    idempotency_key
  )
  where idempotency_key is not null;

alter table public.booking_audit_events enable row level security;

drop policy if exists booking_audit_events_select_participant on public.booking_audit_events;
create policy booking_audit_events_select_participant
on public.booking_audit_events for select to authenticated
using (
  exists (
    select 1 from public.bookings b
    where b.id = booking_id
      and (b.buyer_id = auth.uid() or b.seller_id = auth.uid())
  )
  or public.is_current_user_admin()
);

