create or replace function public.open_booking_dispute(
  p_booking_id uuid,
  p_reason text,
  p_idempotency_key text
) returns public.bookings
language plpgsql security definer set search_path = public as $$
declare v_booking public.bookings%rowtype; v_actor uuid := auth.uid(); v_role text;
begin
  if v_actor is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  if length(trim(coalesce(p_reason, ''))) < 10 then raise exception 'Dispute reason must be at least 10 characters' using errcode = '22023'; end if;
  if nullif(trim(p_idempotency_key), '') is null then raise exception 'Idempotency key required' using errcode = '22023'; end if;
  select * into v_booking from public.bookings where id = p_booking_id for update;
  if not found then raise exception 'Booking not found' using errcode = 'P0002'; end if;
  if v_actor not in (v_booking.buyer_id, v_booking.seller_id) then raise exception 'Only booking participants can dispute' using errcode = '42501'; end if;
  v_role := case when v_actor = v_booking.buyer_id then 'buyer' else 'seller' end;
  if v_booking.status = 'completed' and (v_booking.dispute_deadline_at is null or now() > v_booking.dispute_deadline_at) then raise exception 'Dispute window has closed' using errcode = '23514'; end if;
  if v_booking.status in ('cancelled', 'refunded') then raise exception 'Booking cannot be disputed in its current state' using errcode = '23514'; end if;
  if exists (select 1 from public.booking_audit_events where booking_id = p_booking_id and event_type = 'dispute_opened' and actor_id = v_actor and idempotency_key = p_idempotency_key) then return v_booking; end if;
  perform set_config('app.booking_workflow_rpc', 'on', true);
  update public.bookings set dispute_status = 'open', dispute_opened_at = now(), dispute_opened_by = v_actor, dispute_reason = trim(p_reason)
  where id = p_booking_id returning * into v_booking;
  insert into public.booking_audit_events(booking_id, event_type, actor_id, actor_role, reason, idempotency_key, from_status, to_status)
  values (p_booking_id, 'dispute_opened', v_actor, v_role, trim(p_reason), p_idempotency_key, v_booking.status, v_booking.status);
  return v_booking;
end;
$$;

create or replace function public.auto_confirm_delivered_bookings()
returns integer language plpgsql security definer set search_path = public as $$
declare v_booking public.bookings%rowtype; v_count integer := 0;
begin
  if auth.role() <> 'service_role' then raise exception 'Only the booking scheduler can auto-confirm' using errcode = '42501'; end if;
  for v_booking in
    select * from public.bookings
    where delivery_status = 'seller_claimed' and payment_status = 'paid' and dispute_status <> 'open'
      and completion_due_at <= now() and delivered_schedule_version = schedule_version
      and status in ('confirmed', 'in_progress')
    for update skip locked
  loop
    perform set_config('app.booking_workflow_rpc', 'on', true);
    update public.bookings set status = 'completed', delivery_status = 'buyer_confirmed', completed_at = now(), completed_by = null,
      dispute_deadline_at = now() + interval '48 hours',
      metadata = coalesce(metadata, '{}'::jsonb) || jsonb_build_object('ui_status', 'Completed Service', 'can_rate', true)
    where id = v_booking.id;
    insert into public.booking_audit_events(booking_id, event_type, actor_role, idempotency_key, from_status, to_status)
    values (v_booking.id, 'auto_confirmed_completion', 'system', 'auto-' || v_booking.delivered_schedule_version, v_booking.status, 'completed')
    on conflict do nothing;
    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$$;

create or replace function public.admin_override_booking_status(
  p_booking_id uuid,
  p_action text,
  p_reason text,
  p_idempotency_key text
) returns public.bookings
language plpgsql security definer set search_path = public as $$
declare v_booking public.bookings%rowtype; v_actor uuid := auth.uid(); v_from_status text;
begin
  if v_actor is null or not public.is_current_user_admin() then raise exception 'Administrator access required' using errcode = '42501'; end if;
  if p_action not in ('complete', 'reopen') then raise exception 'Admin action must be complete or reopen' using errcode = '22023'; end if;
  if length(trim(coalesce(p_reason, ''))) < 10 or nullif(trim(p_idempotency_key), '') is null then raise exception 'Reason and idempotency key required' using errcode = '22023'; end if;
  select * into v_booking from public.bookings where id = p_booking_id for update;
  if not found then raise exception 'Booking not found' using errcode = 'P0002'; end if;
  if exists (select 1 from public.booking_audit_events where booking_id = p_booking_id and event_type = 'admin_' || p_action and actor_id = v_actor and idempotency_key = p_idempotency_key) then return v_booking; end if;
  v_from_status := v_booking.status;
  perform set_config('app.booking_workflow_rpc', 'on', true);
  if p_action = 'complete' then
    update public.bookings set status = 'completed', delivery_status = 'buyer_confirmed', completed_at = now(), completed_by = v_actor,
      dispute_deadline_at = now() + interval '48 hours', dispute_status = case when dispute_status = 'open' then 'closed' else dispute_status end,
      metadata = coalesce(metadata, '{}'::jsonb) || jsonb_build_object('ui_status', 'Completed Service', 'can_rate', true)
    where id = p_booking_id returning * into v_booking;
  else
    update public.bookings set status = 'confirmed', delivery_status = 'not_delivered', delivered_at = null, delivered_by = null,
      delivered_schedule_version = null, completion_due_at = null, completed_at = null, completed_by = null, dispute_deadline_at = null,
      metadata = coalesce(metadata, '{}'::jsonb) || jsonb_build_object('ui_status', 'Service Scheduled', 'can_rate', false)
    where id = p_booking_id returning * into v_booking;
  end if;
  insert into public.booking_audit_events(booking_id, event_type, actor_id, actor_role, reason, idempotency_key, from_status, to_status)
  values (p_booking_id, 'admin_' || p_action, v_actor, 'admin', trim(p_reason), p_idempotency_key, v_from_status, v_booking.status);
  return v_booking;
