create or replace function public.protect_booking_workflow_fields()
returns trigger language plpgsql set search_path = public as $$
declare
  v_controlled boolean := coalesce(current_setting('app.booking_workflow_rpc', true), '') = 'on';
begin
  if tg_op = 'UPDATE' and not v_controlled and auth.role() = 'authenticated' then
    if new.delivery_status is distinct from old.delivery_status
      or new.payment_status is distinct from old.payment_status
      or new.cash_collection_status is distinct from old.cash_collection_status
      or new.dispute_status is distinct from old.dispute_status
      or new.delivered_schedule_version is distinct from old.delivered_schedule_version
      or new.delivered_at is distinct from old.delivered_at
      or new.delivered_by is distinct from old.delivered_by
      or new.completion_due_at is distinct from old.completion_due_at
      or new.completed_at is distinct from old.completed_at
      or new.completed_by is distinct from old.completed_by
      or new.dispute_opened_at is distinct from old.dispute_opened_at
      or new.dispute_opened_by is distinct from old.dispute_opened_by
      or new.dispute_reason is distinct from old.dispute_reason
      or new.dispute_deadline_at is distinct from old.dispute_deadline_at
      or new.payment_reference is distinct from old.payment_reference then
      raise exception 'Protected booking fields must be changed through a workflow RPC'
        using errcode = '42501';
    end if;

    if (new.status = 'completed' and old.status <> 'completed')
      or (old.status = 'completed' and new.status not in ('completed', 'refunded')) then
      raise exception 'Completion and reopening must use a workflow RPC'
        using errcode = '42501';
    end if;

    if new.metadata->>'ui_status' in ('Completed Service', 'Service Delivered', 'Refunded')
      and new.metadata->>'ui_status' is distinct from old.metadata->>'ui_status' then
      raise exception 'Terminal UI status is database controlled'
        using errcode = '42501';
    end if;

    if (old.delivery_status <> 'not_delivered' or old.dispute_status = 'open')
      and (
        (new.status is distinct from old.status and not (old.status = 'completed' and new.status = 'refunded'))
        or new.slot_id is distinct from old.slot_id
        or new.start_ts is distinct from old.start_ts
        or new.end_ts is distinct from old.end_ts
      ) then
      raise exception 'Delivered or disputed bookings require a controlled transition'
        using errcode = '42501';
    end if;
  end if;

  if tg_op = 'UPDATE' and (
    new.slot_id is distinct from old.slot_id
    or new.start_ts is distinct from old.start_ts
    or new.end_ts is distinct from old.end_ts
  ) then
    new.schedule_version := old.schedule_version + 1;
  end if;

  return new;
end;
$$;

drop trigger if exists bookings_protect_workflow_fields on public.bookings;
create trigger bookings_protect_workflow_fields
before update on public.bookings
for each row execute function public.protect_booking_workflow_fields();

create or replace function public.validate_review_after_completion()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_booking public.bookings%rowtype;
begin
  select * into v_booking from public.bookings where id = new.booking_id;
  if not found or v_booking.status <> 'completed' then
    raise exception 'Ratings are only allowed after booking completion' using errcode = '23514';
  end if;
  if new.reviewer_id <> v_booking.buyer_id or new.seller_id <> v_booking.seller_id then
    raise exception 'Review participants do not match the completed booking' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists reviews_require_completed_booking on public.reviews;
create trigger reviews_require_completed_booking
before insert or update of booking_id, reviewer_id, seller_id on public.reviews
for each row execute function public.validate_review_after_completion();

create or replace function public.mark_booking_delivered(
  p_booking_id uuid,
  p_idempotency_key text
) returns public.bookings
language plpgsql security definer set search_path = public as $$
declare
  v_booking public.bookings%rowtype;
  v_actor uuid := auth.uid();
begin
  if v_actor is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  if nullif(trim(p_idempotency_key), '') is null then raise exception 'Idempotency key required' using errcode = '22023'; end if;

  select * into v_booking from public.bookings where id = p_booking_id for update;
  if not found then raise exception 'Booking not found' using errcode = 'P0002'; end if;
  if v_booking.seller_id <> v_actor then raise exception 'Only the seller can claim delivery' using errcode = '42501'; end if;
  if exists (select 1 from public.booking_audit_events where booking_id = p_booking_id and event_type = 'seller_delivered' and actor_id = v_actor and idempotency_key = p_idempotency_key) then return v_booking; end if;
  if v_booking.status not in ('confirmed', 'in_progress') or v_booking.delivery_status <> 'not_delivered' then
    raise exception 'Booking is not eligible for delivery' using errcode = '23514';
  end if;
  if v_booking.dispute_status = 'open' then raise exception 'Disputed booking cannot be delivered' using errcode = '23514'; end if;

  perform set_config('app.booking_workflow_rpc', 'on', true);
  update public.bookings set
    delivery_status = 'seller_claimed',
    delivered_at = now(),
    delivered_by = v_actor,
    delivered_schedule_version = schedule_version,
    completion_due_at = now() + interval '72 hours',
    metadata = coalesce(metadata, '{}'::jsonb) || jsonb_build_object('ui_status', 'Service Delivered')
  where id = p_booking_id returning * into v_booking;

  insert into public.booking_audit_events(booking_id, event_type, actor_id, actor_role, idempotency_key, from_status, to_status, event_data)
  values (p_booking_id, 'seller_delivered', v_actor, 'seller', p_idempotency_key, v_booking.status, v_booking.status,
    jsonb_build_object('early_delivery', v_booking.end_ts is not null and now() < v_booking.end_ts, 'schedule_version', v_booking.schedule_version));
  return v_booking;
end;
$$;

create or replace function public.confirm_booking_completion(
  p_booking_id uuid,
  p_idempotency_key text
